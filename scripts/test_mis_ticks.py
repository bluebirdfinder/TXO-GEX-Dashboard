# -*- coding: utf-8 -*-
import os, sys, datetime
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from scripts.mis_session import parse_mis_ticks

TPE = datetime.timezone(datetime.timedelta(hours=8))
D = lambda *a: datetime.datetime(*a, tzinfo=TPE)
def at(b):
    return datetime.datetime.fromtimestamp(b["time"], TPE).strftime("%m-%d %H:%M")

# 日盤：標籤＝結束時間，K 棒開始＝標籤−1 分
r = parse_mis_ticks([["084600", "100", "101", "99", "100.5", "10"], ["084700", "100.5", "102", "100", "101", "20"]], D(2026, 10, 20, 8, 47, 30))
assert [at(b) for b in r] == ["10-20 08:45", "10-20 08:46"], [at(b) for b in r]
assert r[1]["close"] == 101 and r[1]["volume"] == 20

# 夜盤、現在 22:59（本次實測：標籤 '226000' 即 23:00:00；第一列 '150100'）
r = parse_mis_ticks([["150100", "46490", "46557", "46476", "46500", "363"], ["225900", "1", "2", "1", "2", "3"], ["226000", "46980", "46982", "46960", "46964", "35"]], D(2026, 10, 20, 22, 59, 40))
assert [at(b) for b in r] == ["10-20 15:00", "10-20 22:58", "10-20 22:59"], [at(b) for b in r]

# 夜盤跨午夜（標籤回到 0000 起算）：現在 00:12
ticks = [["235900", "10", "11", "9", "10", "1"], ["000000", "10", "11", "9", "10", "1"], ["000100", "10", "11", "9", "10", "1"], ["001200", "10", "11", "9", "10", "1"]]
r = parse_mis_ticks([["150100", "10", "11", "9", "10", "1"]] + ticks, D(2026, 10, 21, 0, 12, 20))
assert [at(b) for b in r] == ["10-20 15:00", "10-20 23:58", "10-20 23:59", "10-21 00:00", "10-21 00:11"], [at(b) for b in r]

# 夜盤跨午夜（標籤連續編號 24xxxx）
ticks = [["235900", "10", "11", "9", "10", "1"], ["240000", "10", "11", "9", "10", "1"], ["240100", "10", "11", "9", "10", "1"], ["241200", "10", "11", "9", "10", "1"]]
r = parse_mis_ticks(ticks, D(2026, 10, 21, 0, 12, 20))
assert [at(b) for b in r] == ["10-20 23:58", "10-20 23:59", "10-21 00:00", "10-21 00:11"], [at(b) for b in r]

# 壞資料不補：價格 0、缺欄位、非數字都丟掉
r = parse_mis_ticks([["090000", "0", "0", "0", "0", "0"], ["090100", "x", "1", "1", "1", "1"], ["090200"], ["090300", "5", "6", "4", "5", "2"]], D(2026, 10, 20, 9, 3, 30))
assert len(r) == 1 and at(r[0]) == "10-20 09:02", [at(b) for b in r]
assert parse_mis_ticks(None, D(2026, 10, 20, 9, 0, 0)) == [] and parse_mis_ticks([], D(2026, 10, 20, 9, 0, 0)) == []
# 換分鐘瞬間同一分鐘出現兩列（'225900' 與 '226000' 都代表 23:00 結束的前一分鐘區段時，保留較新的一列）
r = parse_mis_ticks([["225800", "1", "2", "1", "1.5", "1"], ["225900", "1", "2", "1", "1.5", "7"], ["225900", "1", "3", "1", "2.5", "9"]], D(2026, 10, 20, 22, 59, 30))
assert [at(b) for b in r] == ["10-20 22:57", "10-20 22:58"] and r[1]["volume"] == 9, r
print("mis ticks: all tests passed")
